export type RouteKey = keyof typeof routes;

export function path(locale: Locale, key: RouteKey, slug?: string): string {
  const seg = routes[key];
  const base = seg ? `/${locale}/${seg}` : `/${locale}`;
  return slug ? `${base}/${slug}` : base;
}

